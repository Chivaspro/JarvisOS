"""Reverse engineering & remake — capture real evidence, then rebuild clean.

REA (``mcp_host/rea.py``) inspects software and returns findings with their
Evidence; it deliberately never produces a runnable copy of anything. This
module is the missing half: it captures what a page or app is made of, then
builds a *clean-room reproduction* from that evidence.

Four actions, one pipeline:

* ``capture``     — Playwright records the DOM, a screenshot, the computed
  styles of the landmarks and the page's own network traffic (HAR 1.2) into
  ``data/workspaces/rea/<domain>/<run>/capture/``.
* ``api_surface`` — the captured traffic is reduced to an API spec: method,
  path, statuses, query keys and content type per endpoint.
* ``remake``      — the evidence is handed to the same synthesis provider chain
  the Skill Forge uses, and the reply's ``=== FILE: name ===`` blocks are
  written as a standalone project, then verified (files non-empty, the HTML is
  real markup, every Python file parses). This is the "copy" — original code
  written from evidence, never a byte-for-byte lift of the target.
* ``reconstruct`` — a local JS/Electron app folder is copied into a readable
  project tree; when the REA server is connected, its source-recovery tool is
  asked about compiled bundles too.

Three rules are enforced here and nowhere else:

* **Authorization is explicit.** Every action that touches a live target or
  copies an app refuses without ``authorized=true`` — the user's own statement
  that they own the software or are allowed to examine it. Each run is written
  to ``audit.log`` beside the artifacts (the same policy as the vault's
  ``jarvis_rea.py``).
* **Captured content is evidence, never instructions.** Nothing in a DOM, a
  HAR or a recovered file is executed or followed; the model is told the same
  in every result.
* **Nothing is installed and nothing leaves the workspace** unless the caller
  names its own ``destination``.
"""

from __future__ import annotations

import json
import re
import time
from urllib.parse import parse_qsl, urlparse
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable

__all__ = ["extract_api_surface", "parse_file_blocks", "run"]

_CONTROLLER = "reverse-engineer"

#: How long capture waits for the browser lock before giving up. A capture
#: navigates the one shared page, so it must not interleave with a workflow.
_BROWSER_WAIT_S = 20.0

#: What the remake synthesis is handed and allowed to produce.
_MAX_DOM_FOR_PROMPT = 8000
_MAX_ENDPOINTS_FOR_PROMPT = 12
_MAX_FILES = 40
_MAX_FILE_BYTES = 400_000

#: Extensions a synthesised remake may contain. Anything else is rejected, so
#: a stray block can never write an executable or an unexpected format.
_ALLOWED_EXTENSIONS = frozenset({
    ".html", ".htm", ".css", ".js", ".mjs", ".cjs", ".jsx", ".ts", ".tsx",
    ".py", ".json", ".md", ".txt", ".svg", ".yml", ".yaml",
})

#: What ``reconstruct`` copies out of an app folder (source-shaped text only).
_COPY_EXTENSIONS = _ALLOWED_EXTENSIONS | {".map", ".scss", ".less"}
_COPY_MAX_FILES = 600
_COPY_MAX_BYTES = 12_000_000
_SKIP_DIRS = frozenset({"node_modules", ".git", "__pycache__", ".cache",
                        "dist", "build", ".venv", "venv", ".pytest_cache"})

#: Paths in the captured traffic that read as an API rather than a document.
_API_HINTS = ("/api/", "/graphql", "graphql", "/v1/", "/v2/", "/v3/", "/v4/",
              "/rest/", "/rpc", "/gql", "/query", "/_next/data/")
_STATIC_RE = re.compile(
    r"\.(?:png|jpe?g|gif|webp|avif|svg|ico|woff2?|ttf|otf|eot|css|map)$",
    re.IGNORECASE)

_SYSTEM = '''You are the J.A.R.V.I.S. clean-room remake architect. You are given
evidence captured from a website — a DOM excerpt, computed styles and the API
endpoints its own traffic revealed — and your job is to write a clean, original,
standalone reproduction of the page in modern, readable code.

Rules (non-negotiable):
1. Write ORIGINAL code. Never paste long verbatim text from the target; rewrite
   generic copy in your own words and keep only short UI labels that the layout
   genuinely needs.
2. No tracking scripts, no analytics, no third-party embeds. Tailwind CSS via
   its CDN is allowed for styling; small hand-written CSS is preferred.
3. When the evidence lists API endpoints, include a small mock backend
   (server.py) that serves them with realistic sample data using ONLY the
   Python standard library (http.server). Omit it when there are no endpoints.
4. Output ONLY the files, each as one block starting with a line of the form
   `=== FILE: <name> ===`. Produce at most 6 files. `index.html` is required.
   Prefer these names: index.html, styles.css, app.js, server.py, README.md.
5. The last line of index.html must be an HTML comment saying it is a
   clean-room remake generated by J.A.R.V.I.S. from captured evidence, not a
   copy of the original site.
'''


# ── workspace, audit and small helpers ────────────────────────────────────────

def _workspace_root() -> Path:
    """``data/workspaces/rea`` — the same root REA's evidence bundles use."""
    try:
        from mcp_host.rea import artifact_dir
        return artifact_dir()
    except Exception:
        root = Path(__file__).resolve().parent.parent / "data" / "workspaces" / "rea"
        root.mkdir(parents=True, exist_ok=True)
        return root


def _log(message: str) -> None:
    try:
        from observability.logger import log_event
        log_event("INFO", "capabilities", "reverse_engineer",
                  detail=str(message)[:400])
        return
    except Exception:
        pass
    try:
        print(f"[ReverseEngineer] {message}")
    except Exception:
        pass


def _audit(action: str, target: str, destination: str = "") -> None:
    """Append one line to the run log beside the artifacts. Never fatal."""
    try:
        line = (f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}"
                f" | {action} | target={target or '-'}"
                f" | destination={destination or '-'}\n")
        with (_workspace_root() / "audit.log").open("a", encoding="utf-8") as fh:
            fh.write(line)
    except Exception:
        pass


def _authorized(args: dict) -> bool:
    """The user's explicit authorization, in any shape a model sends it."""
    value = (args or {}).get("authorized")
    if isinstance(value, bool):
        return value
    return str(value or "").strip().lower() in ("true", "yes", "1", "authorized")


def _untrusted(text: str) -> str:
    """Prefix target-derived content with the evidence-only banner REA uses."""
    try:
        from mcp_host.rea import with_untrusted_banner
        return with_untrusted_banner(str(text))
    except Exception:
        return str(text)


def _reporter(on_event) -> Callable[[str], None]:
    """The module's progress sink: a no-op unless the caller supplied one."""
    if not callable(on_event):
        return lambda _text: None

    def report(text: str) -> None:
        try:
            on_event(str(text)[:120])
        except Exception:
            pass

    return report


def _refused(what: str, target: str) -> dict:
    return {
        "ok": False, "controller": _CONTROLLER, "reason": "refused",
        "detail": (f"I need the user's explicit confirmation before I {what} "
                   f"\u201c{target}\u201d. Reverse engineering and copying are "
                   f"only for software they own or are authorized to examine — "
                   f"ask them to confirm, then call again with authorized=true."),
        "evidence": {},
    }


def _fail(detail: str, *, reason: str = "action_failed", path: str = "") -> dict:
    out = {"ok": False, "controller": _CONTROLLER, "reason": reason,
           "detail": detail, "evidence": {}}
    if path:
        out["path"] = path
        out["evidence"]["path"] = path
    return out


def _domain_of(value: str) -> str:
    """A filesystem-safe name for a URL's host (or a folder name)."""
    text = str(value or "").strip()
    host = ""
    try:
        if "//" in text:
            host = urlparse(text).netloc or ""
    except Exception:
        host = ""
    host = host.split("@")[-1] if host else text
    clean = re.sub(r"[^A-Za-z0-9._-]+", "_", str(host)).strip("._-")
    return (clean or "target")[:80]


def _run_id() -> str:
    return time.strftime("%Y%m%d-%H%M%S", time.localtime())


def _read_text(path: Path, limit: int = 0) -> str:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""
    return text[:limit] if limit else text


def _read_json(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8", errors="replace"))
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def _find_file(base: Path, name: str) -> Path | None:
    """Locate *name* in a capture folder, its ``capture/`` child, or as itself."""
    candidates: list[Path] = []
    if base.is_file():
        if base.name == name:
            candidates.append(base)
    else:
        candidates += [base / name, base / "capture" / name]
    for candidate in candidates:
        try:
            if candidate.is_file():
                return candidate
        except OSError:
            continue
    return None


def _write_manifest(run_dir: Path, *, target: str, kind: str, **extra) -> Path | None:
    """One provenance document per run: what was made, from what, and when."""
    data = {"kind": kind, "target": str(target or ""),
            "at": time.time(),
            "at_iso": datetime.now(timezone.utc).isoformat(),
            "tool": "reverse_engineer", **extra}
    path = Path(run_dir) / (f"{kind}_manifest.json" if kind == "remake"
                            else "manifest.json")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")
        return path
    except Exception:
        return None


# ── API surface extraction (pure) ─────────────────────────────────────────────

def extract_api_surface(har: dict) -> dict:
    """Reduce a captured HAR document to the API signatures it contained.

    One row per (method, path): statuses seen, query keys, content type and the
    resource type that produced it. Static assets are excluded, so a remake
    prompt gets endpoints rather than every image on the page.
    """
    entries = ((har or {}).get("log") or {}).get("entries") or []
    rows: dict[tuple[str, str], dict] = {}
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        request = entry.get("request") or {}
        response = entry.get("response") or {}
        url = str(request.get("url") or "")
        if not url:
            continue
        method = str(request.get("method") or "GET").upper()
        parsed = urlparse(url)
        path = parsed.path or "/"
        resource_type = str(entry.get("_resourceType") or "")
        content_type = ""
        for header in response.get("headers") or []:
            if str(header.get("name") or "").lower() == "content-type":
                content_type = str(header.get("value") or "")
                break
        lower_path = path.lower()
        is_json = ("json" in content_type.lower()
                   or lower_path.endswith(".json"))
        looks_api = (resource_type in ("xhr", "fetch")
                     or any(hint in lower_path for hint in _API_HINTS)
                     or is_json)
        if not looks_api:
            continue
        if _STATIC_RE.search(path) and not is_json:
            continue
        query_keys = [key for key, _value in parse_qsl(parsed.query)][:20]
        key = (method, path)
        row = rows.get(key)
        if row is None:
            row = {"method": method, "path": path, "statuses": [],
                   "query_keys": query_keys, "content_type": content_type,
                   "resource_type": resource_type, "sample_url": url}
            rows[key] = row
        status = response.get("status")
        if status and status not in row["statuses"]:
            row["statuses"].append(status)
        for query_key in query_keys:
            if query_key not in row["query_keys"]:
                row["query_keys"].append(query_key)
    ordered = sorted(rows.values(), key=lambda r: (r["path"], r["method"]))
    return {"endpoint_count": len(ordered), "endpoints": ordered}


def _write_api_spec(capture_dir: Path, run_dir: Path,
                    target_url: str = "") -> dict:
    """Read a capture's HAR, extract the API surface, and record it as JSON."""
    har = _read_json(Path(capture_dir) / "network.har")
    spec = extract_api_surface(har)
    spec["target"] = str(target_url or "")
    spec["captured_at"] = time.time()
    spec["capture_dir"] = str(capture_dir)
    path = Path(run_dir) / "api_spec.json"
    try:
        path.write_text(json.dumps(spec, indent=2), encoding="utf-8")
        spec["path"] = str(path)
    except OSError:
        spec["path"] = ""
    return spec


# ── capture ───────────────────────────────────────────────────────────────────

def _capture_via_browser(url: str, capture_dir: Path) -> dict:
    """One capture through the shared Playwright session, under the browser lock."""
    from capabilities import browser_pw, locks
    lock = locks.get_lock("browser")
    try:
        lock.acquire(owner="reverse_engineer:capture", timeout_s=_BROWSER_WAIT_S)
    except locks.ControlBusy as busy:
        return {"ok": False, "controller": "playwright", "reason": "lock_busy",
                "detail": (f"The browser is busy with another task, so I did not "
                           f"capture anything ({busy})."),
                "evidence": {}}
    try:
        return browser_pw.run("browser_capture",
                              {"url": url, "path": str(capture_dir)})
    finally:
        try:
            lock.release()
        except Exception:
            pass


def _capture_to(url: str, base: Path | None = None) -> dict:
    """Run one capture into a fresh run folder. Returns every path involved."""
    domain = _domain_of(url)
    root = Path(base) if base is not None else _workspace_root()
    run_dir = root / domain / _run_id()
    capture_dir = run_dir / "capture"
    try:
        capture_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return {"ok": False, "domain": domain, "run_dir": run_dir,
                "capture_dir": capture_dir,
                "browser": {"ok": False, "reason": "action_failed",
                            "detail": f"The capture folder could not be created: {exc}",
                            "evidence": {}}}
    browser = _capture_via_browser(url, capture_dir)
    return {"ok": bool(browser.get("ok")), "domain": domain, "run_dir": run_dir,
            "capture_dir": capture_dir, "browser": browser}


def _capture_failure(outcome: dict) -> dict:
    browser = outcome.get("browser") or {}
    return _fail(
        f"The capture did not run: {browser.get('detail') or 'the browser did not answer'}",
        reason=str(browser.get("reason") or "action_failed"),
        path=str(outcome.get("run_dir") or ""))


def _h_capture(args: dict, report: Callable[[str], None]) -> dict:
    """``capture`` — record a page as evidence in the workspace."""
    url = str(args.get("url") or "").strip()
    if not url:
        return _fail("capture needs a 'url' naming the page to record.")
    if not _authorized(args):
        return _refused("capture", url)
    destination = str(args.get("destination") or "").strip()
    report("Capturing the page with Playwright")
    outcome = _capture_to(url, Path(destination) if destination else None)
    if not outcome["ok"]:
        return _capture_failure(outcome)
    report("Reading the API surface out of the captured traffic")
    spec = _write_api_spec(outcome["capture_dir"], outcome["run_dir"], url)
    browser_evidence = (outcome["browser"].get("evidence") or {})
    _write_manifest(outcome["run_dir"], target=url, kind="capture",
                    domain=outcome["domain"],
                    capture_dir=str(outcome["capture_dir"]),
                    endpoints=spec.get("endpoint_count", 0),
                    requests=browser_evidence.get("requests", 0),
                    browser_detail=str(outcome["browser"].get("detail") or ""))
    _audit("capture", url, str(outcome["run_dir"]))
    _log(f"capture {url} -> {outcome['run_dir']} "
         f"({spec.get('endpoint_count', 0)} endpoint signature(s))")
    detail = (f"Captured {url}: evidence saved under {outcome['run_dir']} — "
              f"{spec.get('endpoint_count', 0)} API endpoint signature(s) in "
              f"api_spec.json. Run remake with this folder (or the same URL) to "
              f"build a clean reproduction.")
    return {
        "ok": True, "controller": _CONTROLLER, "reason": "", "detail": detail,
        "evidence": {
            "path": str(outcome["run_dir"]),
            "capture_dir": str(outcome["capture_dir"]),
            "api_spec": spec.get("path", ""),
            "endpoints": spec.get("endpoint_count", 0),
            "requests": browser_evidence.get("requests", 0),
        },
        "path": str(outcome["run_dir"]),
        "endpoints": spec.get("endpoint_count", 0),
    }


# ── API surface ───────────────────────────────────────────────────────────────

def _h_api_surface(args: dict, report: Callable[[str], None]) -> dict:
    """``api_surface`` — the endpoints a capture revealed."""
    url = str(args.get("url") or "").strip()
    path = str(args.get("path") or "").strip()
    if path:
        har = _find_file(Path(path).expanduser(), "network.har")
        if har is None:
            return _fail("No network.har was found there — point me at a "
                         "capture folder, or give me a 'url' to capture first.")
        capture_dir = har.parent
        run_dir = (capture_dir.parent if capture_dir.name == "capture"
                   else capture_dir)
        spec = _write_api_spec(capture_dir, run_dir, url)
    elif url:
        if not _authorized(args):
            return _refused("capture and analyze", url)
        report("Capturing the page with Playwright")
        outcome = _capture_to(url)
        if not outcome["ok"]:
            return _capture_failure(outcome)
        spec = _write_api_spec(outcome["capture_dir"], outcome["run_dir"], url)
        _audit("api_surface", url, str(outcome["run_dir"]))
    else:
        return _fail("api_surface needs a 'url' to capture or the 'path' of an "
                     "existing capture folder.")

    rows = list(spec.get("endpoints") or [])
    listing = "\n".join(f"- {row['method']} {row['path']}"
                        for row in rows[:12])
    # Endpoint paths are captured target content: the banner keeps the model
    # reading them as evidence, never as instructions to follow.
    detail = _untrusted(
        f"{len(rows)} API endpoint signature(s) found in the captured "
        f"traffic." + (f"\n{listing}" if listing else " None were observed."))
    return {
        "ok": True, "controller": _CONTROLLER, "reason": "", "detail": detail,
        "evidence": {"path": spec.get("path", ""),
                     "endpoints": len(rows)},
        "path": spec.get("path", ""),
        "endpoints": rows[:50],
        "api_spec": spec,
    }


# ── remake (the clean-room synthesis) ─────────────────────────────────────────

_FILE_BLOCK_RE = re.compile(r"^===+\s*FILE:\s*(.+?)\s*===+\s*$",
                            re.IGNORECASE | re.MULTILINE)


def parse_file_blocks(text: str) -> dict[str, str]:
    """Every ``=== FILE: name ===`` block in a model reply, fences stripped."""
    raw = str(text or "")
    matches = list(_FILE_BLOCK_RE.finditer(raw))
    files: dict[str, str] = {}
    for index, match in enumerate(matches):
        name = match.group(1).strip().strip("`\"'")
        end = matches[index + 1].start() if index + 1 < len(matches) else len(raw)
        body = raw[match.end():end].strip()
        if body.startswith("```"):
            body = re.sub(r"^```[A-Za-z0-9_+-]*\s*\n?", "", body)
            body = re.sub(r"\n?```\s*$", "", body).strip()
        if name and body and name not in files:
            files[name] = body
    if not files:
        # A second shape some models fall back to: one JSON object with a
        # "files" map. Same outcome, still only ever written to the workspace.
        try:
            from evolution import forge
            data = forge.parse_json_response(raw)
            candidate = data.get("files")
            if isinstance(candidate, dict):
                files = {str(k): str(v) for k, v in candidate.items()
                         if isinstance(v, str) and v.strip()}
        except Exception:
            pass
    return files


def _safe_file_name(name: str) -> str:
    """A bare, non-hidden file name with an allowed extension — or ''."""
    clean = str(name or "").strip().replace("\\", "/").split("/")[-1]
    clean = clean.strip().strip("`\"'")
    clean = re.sub(r"[^A-Za-z0-9._-]+", "_", clean)
    if not clean or clean.startswith("."):
        return ""
    if Path(clean).suffix.lower() not in _ALLOWED_EXTENSIONS:
        return ""
    return clean[:80]


def _write_project_files(files: dict[str, str], out_dir: Path) -> tuple[list[str], list[str]]:
    """Write the accepted files (never outside *out_dir*). Returns written/skipped."""
    try:
        out_dir.mkdir(parents=True, exist_ok=True)
    except OSError:
        return [], sorted(files)
    written: list[str] = []
    skipped: list[str] = []
    for name in sorted(files):
        body = files[name]
        safe = _safe_file_name(name)
        if (not safe or len(written) >= _MAX_FILES
                or len(body.encode("utf-8", "replace")) > _MAX_FILE_BYTES):
            skipped.append(name)
            continue
        try:
            (out_dir / safe).write_text(
                body if body.endswith("\n") else body + "\n", encoding="utf-8")
            written.append(safe)
        except OSError:
            skipped.append(name)
    return written, skipped


def _verify_project(out_dir: Path, written: list[str]) -> dict:
    """Check what was actually written: real markup, parseable Python, no empties."""
    checks: dict = {"files_written": len(written), "index_html": False,
                    "python_ok": True, "empty_files": []}
    index = Path(out_dir) / "index.html"
    if index.is_file():
        text = _read_text(index).lower()
        checks["index_html"] = any(marker in text for marker in
                                   ("<!doctype", "<html", "<body", "<div"))
    import ast as _ast
    for name in written:
        path = Path(out_dir) / name
        body = _read_text(path)
        if not body.strip():
            checks["empty_files"].append(name)
        if path.suffix.lower() == ".py":
            try:
                _ast.parse(body)
            except SyntaxError as exc:
                checks["python_ok"] = False
                checks.setdefault("python_errors", []).append(
                    f"{name}: line {exc.lineno}: {exc.msg}")
    return checks


def _synthesize_project(*, dom_text: str, spec: dict, feature: str,
                        target: str, out_dir: Path) -> dict:
    """Ask the synthesis chain for a clean project and write it, verified."""
    endpoints = list(spec.get("endpoints") or [])[:_MAX_ENDPOINTS_FOR_PROMPT]
    focus = feature or ("the whole page — layout, styling, main sections and "
                        "interactions")
    prompt = (
        f"Target: {target}\n"
        f"Focus feature: {focus}\n\n"
        f"DOM excerpt (first {_MAX_DOM_FOR_PROMPT} characters):\n"
        f"```html\n{dom_text}\n```\n\n"
        f"API endpoints observed in the captured traffic "
        f"({spec.get('endpoint_count', 0)} total):\n"
        f"```json\n{json.dumps(endpoints, indent=2)}\n```\n\n"
        "Write the remake now."
    )
    try:
        from evolution import forge
        raw, provider = forge._ask_model(prompt, _SYSTEM, None)
    except Exception as exc:
        return {"ok": False,
                "message": f"The remake synthesis could not run: {exc}"}
    files = parse_file_blocks(raw)
    if not files:
        return {"ok": False,
                "message": ("The model replied without any === FILE: name === "
                            "blocks, so nothing was written.")}
    written, skipped = _write_project_files(files, Path(out_dir))
    if not written:
        return {"ok": False,
                "message": ("Every generated file was rejected (empty, too "
                            "large, or an unsupported name), so nothing was "
                            "written.")}
    checks = _verify_project(Path(out_dir), written)
    return {"ok": True, "files": written, "skipped": skipped,
            "checks": checks, "provider": str(provider or "")}


def _h_remake(args: dict, report: Callable[[str], None]) -> dict:
    """``remake`` — a clean, verified project synthesised from the evidence."""
    url = str(args.get("url") or "").strip()
    path = str(args.get("path") or "").strip()
    destination = str(args.get("destination") or "").strip()
    feature = str(args.get("feature") or "").strip()

    spec: dict
    if url:
        if not _authorized(args):
            return _refused("capture and remake", url)
        report("Capturing the page with Playwright")
        outcome = _capture_to(url)
        if not outcome["ok"]:
            return _capture_failure(outcome)
        run_dir, capture_dir = outcome["run_dir"], outcome["capture_dir"]
        spec = _write_api_spec(capture_dir, run_dir, url)
        target_label = url
        _audit("remake-capture", url, str(run_dir))
    elif path:
        dom = _find_file(Path(path).expanduser(), "dom.html")
        if dom is None:
            return _fail("remake reads a capture folder and none was found "
                         "there (no dom.html), and no 'url' was given to "
                         "capture first.")
        capture_dir = dom.parent
        run_dir = (capture_dir.parent if capture_dir.name == "capture"
                   else capture_dir)
        spec = (_write_api_spec(capture_dir, run_dir)
                if (capture_dir / "network.har").is_file()
                else {"endpoint_count": 0, "endpoints": []})
        target_label = str(path)
    else:
        return _fail("remake needs a 'url' (it captures first) or the 'path' "
                     "of a capture folder.")

    dom_text = _read_text(capture_dir / "dom.html", _MAX_DOM_FOR_PROMPT)
    if not dom_text.strip():
        return _fail("The captured DOM is empty, so there is nothing to remake.")
    out_dir = (Path(destination).expanduser() if destination
               else run_dir / "remake")
    report("Asking the model for a clean remake, then verifying what it wrote")
    synth = _synthesize_project(dom_text=dom_text, spec=spec, feature=feature,
                                target=target_label, out_dir=out_dir)
    if not synth.get("ok"):
        return _fail(str(synth.get("message") or "The remake failed."),
                     reason="unavailable", path=str(out_dir))

    checks = dict(synth.get("checks") or {})
    files = list(synth.get("files") or [])
    verified = (bool(checks.get("index_html")) and bool(checks.get("python_ok"))
                and not checks.get("empty_files"))
    _write_manifest(out_dir, target=target_label, kind="remake", feature=feature,
                    provider=synth.get("provider", ""), files=files,
                    checks=checks, capture_dir=str(capture_dir))
    _audit("remake", target_label, str(out_dir))
    _log(f"remake {target_label} -> {out_dir} ({len(files)} file(s), "
         f"verified={verified})")
    detail = (f"Remade \u201c{target_label}\u201d with {synth.get('provider')}: "
              f"{len(files)} file(s) written to {out_dir}")
    if verified:
        detail += " and verified (index.html present, Python files parse, no empty files)."
    else:
        detail += (". The project did NOT fully pass verification — inspect it "
                   f"before running: {json.dumps(checks)}")
    if synth.get("skipped"):
        detail += f" Skipped {len(synth['skipped'])} rejected file name(s)."
    return {
        "ok": verified, "controller": _CONTROLLER,
        "reason": "" if verified else "unverified", "detail": detail,
        "evidence": {"path": str(out_dir), "files": len(files),
                     "provider": str(synth.get("provider") or ""),
                     "verified": verified},
        "path": str(out_dir), "files": files, "checks": checks,
    }


# ── reconstruct (copy an app's own sources into a readable tree) ──────────────

def _copy_app_tree(src: Path, dest: Path) -> dict:
    """Copy source-shaped text files out of an app folder, bounded and counted."""
    import shutil
    files = 0
    total = 0
    truncated = False
    for item in sorted(src.rglob("*")):
        if not item.is_file():
            continue
        try:
            relative = item.relative_to(src)
        except ValueError:
            continue
        if any(part in _SKIP_DIRS for part in relative.parts[:-1]):
            continue
        if item.suffix.lower() not in _COPY_EXTENSIONS:
            continue
        try:
            size = item.stat().st_size
        except OSError:
            continue
        if files >= _COPY_MAX_FILES or total + size > _COPY_MAX_BYTES:
            truncated = True
            continue
        target = dest / relative
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, target)
            files += 1
            total += size
        except OSError:
            continue
    return {"files": files, "bytes": total, "truncated": truncated}


_PATH_ARG_NAMES = ("path", "input", "target", "artifact", "file", "directory",
                   "app", "source", "bundle", "root")


def _rea_arguments(schema: dict, value: Path) -> dict | None:
    """Arguments for a REA tool, built from its own discovered schema.

    The tool's input profile changes between REA releases; guessing a parameter
    name would produce a failed call that looks like a broken feature. The
    schema is authoritative: a path-like property is found by name, and any
    required property that cannot be filled makes the whole attempt not run.
    """
    properties = dict((schema or {}).get("properties") or {})
    arguments: dict = {}
    for name in _PATH_ARG_NAMES:
        if name in properties:
            arguments[name] = str(value)
            break
    if not arguments:
        return None
    required = [str(item) for item in (schema or {}).get("required") or []]
    if any(item not in arguments for item in required):
        return None
    return arguments


def _rea_recovery(src: Path, out_dir: Path) -> dict:
    """Ask a connected REA server for source recovery, if it offers it."""
    tool = None
    try:
        from mcp_host.manager import get_manager
        manager = get_manager()
        for item in manager.tools():
            if (item.get("server") == "rea"
                    and item.get("tool") == "recover_javascript_sources"):
                tool = item
                break
    except Exception:
        manager, tool = None, None
    if tool is None:
        return {"attempted": False, "ok": False,
                "note": ("REA is not connected, so only the plain copy ran; "
                         "enable the REA server for source recovery of "
                         "compiled bundles.")}
    arguments = _rea_arguments(tool.get("schema") or {}, src)
    if arguments is None:
        return {"attempted": False, "ok": False,
                "note": ("REA's recovery tool did not declare a usable path "
                         "argument, so only the plain copy ran.")}
    try:
        result = manager.call_tool("rea", "recover_javascript_sources",
                                   arguments, timeout=240)
    except Exception as exc:
        return {"attempted": True, "ok": False,
                "note": f"REA recovery failed: {exc}"}
    if not getattr(result, "ok", False):
        error = getattr(result, "error", "") or "no reason given"
        return {"attempted": True, "ok": False,
                "note": f"REA recovery failed: {error}"}
    text = str(getattr(result, "text", "") or "")
    path = Path(out_dir) / "rea_recovery.md"
    try:
        path.write_text(text, encoding="utf-8")
    except OSError:
        path = None
    return {"attempted": True, "ok": True,
            "note": (f"REA source recovery ran and its output was saved to {path}."
                     if path else "REA source recovery ran."),
            "file": str(path) if path else ""}


def _h_reconstruct(args: dict, report: Callable[[str], None]) -> dict:
    """``reconstruct`` — copy an app folder's own sources into the workspace."""
    path = str(args.get("path") or "").strip()
    if not path:
        return _fail("reconstruct needs the 'path' of the app folder to copy.")
    if not _authorized(args):
        return _refused("copy", path)
    src = Path(path).expanduser()
    if not src.exists():
        return _fail(f"That target does not exist: {src}")
    if src.is_file():
        return _fail("reconstruct copies an extracted app folder. For a single "
                     "compiled file, enable the REA server and use its "
                     "rea__recover_javascript_sources and analysis tools.")
    destination = str(args.get("destination") or "").strip()
    run_dir = _workspace_root() / _domain_of(src.name or "app") / _run_id()
    dest = (Path(destination).expanduser() if destination
            else run_dir / "reconstruct" / "app")
    try:
        dest.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return _fail(f"The reconstruction folder could not be created: {exc}")
    report("Copying the app's own source files into the workspace")
    copy = _copy_app_tree(src, dest)
    if copy["files"] == 0:
        return _fail(f"No viewable source files were found under {src.name}, "
                     f"so nothing was copied.")
    report("Checking REA for source recovery")
    recovery = _rea_recovery(src, dest.parent)
    _write_manifest(run_dir, target=str(src), kind="reconstruct",
                    copied=copy["files"], bytes=copy["bytes"],
                    truncated=copy["truncated"],
                    rea_recovery=recovery.get("note", ""))
    _audit("reconstruct", str(src), str(dest))
    _log(f"reconstruct {src} -> {dest} ({copy['files']} file(s))")
    detail = (f"Copied {copy['files']} source file(s) ({copy['bytes']} bytes) "
              f"from {src.name} into {dest}.")
    if copy["truncated"]:
        detail += (" The copy hit its size or count cap, so it is a partial "
                   "tree — the manifest records the run.")
    detail += f" {recovery.get('note', '')}".rstrip()
    return {
        "ok": True, "controller": _CONTROLLER, "reason": "", "detail": detail,
        "evidence": {"path": str(dest), "files": copy["files"],
                     "bytes": copy["bytes"], "truncated": copy["truncated"],
                     "rea_recovery": bool(recovery.get("ok"))},
        "path": str(dest), "files": copy["files"],
    }


