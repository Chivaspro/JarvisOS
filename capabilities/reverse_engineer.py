_HANDLERS = {
    "capture": _h_capture,
    "api_surface": _h_api_surface,
    "remake": _h_remake,
    "reconstruct": _h_reconstruct,
}


def run(action_name: str, args: dict | None = None, on_event=None) -> dict:
    """Execute one reverse-engineering action. Returns a result dict, never raises.

    ``on_event`` (optional) receives the REAL phase sentences this pipeline is
    in — "Capturing the page with Playwright", "Asking the model for a clean
    remake…" — so a capture or remake that runs for minutes is visible in the
    activity row while it happens, never as a fabricated percentage.
    """
    handler = _HANDLERS.get(str(action_name or "").strip())
    if handler is None:
        return {"ok": False, "controller": _CONTROLLER, "reason": "unknown_action",
                "detail": (f"'{action_name}' is not a reverse-engineering action "
                           f"(one of: {', '.join(_HANDLERS)})."),
                "evidence": {}}
    try:
        return handler(dict(args or {}), _reporter(on_event))
    except Exception as exc:
        _log(f"action {action_name} crashed: {type(exc).__name__}: {exc}")
        return {"ok": False, "controller": _CONTROLLER, "reason": "crashed",
                "detail": (f"The reverse-engineering action failed: "
                           f"{type(exc).__name__}: {exc}"),
                "evidence": {}}
